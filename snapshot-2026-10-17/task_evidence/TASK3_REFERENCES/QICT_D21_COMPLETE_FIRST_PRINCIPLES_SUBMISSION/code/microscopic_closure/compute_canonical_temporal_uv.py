D=(10,9,8)
TARGET=6.7275437569502613155

# C8 split-step symbol U(k)=exp(-ikx sx) exp(-iky sy) exp(-ikz sz).
# For U in SU(2), eigenvalues are exp(+-i theta), with
# cos(theta)=cos kx cos ky cos kz - sin kx sin ky sin kz.
# The canonical temporal monodromy completion is P_a(k)=U(k)^d_a.
# The 6x6 route-family compression is
# T=(U^10⊗I + U^9⊗X + U^8⊗Z)/3.
# Left multiplication by U^8 is unitary. In the U eigenbasis it splits into
# B(lambda)=(lambda^2 I + lambda X + Z)/3 and B(lambda^-1).
# det(lambda^2 I+lambda X+Z)=lambda^6+lambda^3+1,
# hence kappa(k)=-1/12 log det(T†T)
# = log 3 -(1/3) log|1+2 cos(3 theta(k))|.

def kappa_from_unit_cube(points: np.ndarray) -> np.ndarray:
    k=-math.pi+2*math.pi*points
    c=np.cos(k); s=np.sin(k)
    costheta=c[:,0]*c[:,1]*c[:,2]-s[:,0]*s[:,1]*s[:,2]
    costheta=np.clip(costheta,-1.0,1.0)
    theta=np.arccos(costheta)
    den=np.abs(1.0+2.0*np.cos(3.0*theta))
    den=np.maximum(den,1e-300)
    return math.log(3.0)-(1.0/3.0)*np.log(den)

def sobol_mean(m:int,seed:int):
    sampler=qmc.Sobol(d=3,scramble=True,seed=seed)
    pts=sampler.random_base2(m)
    vals=kappa_from_unit_cube(pts)
    return {
        'seed':seed,'m':m,'samples':int(2**m),
        'mean':float(vals.mean()),
        'std_error_naive':float(vals.std(ddof=1)/math.sqrt(len(vals))),
        'min':float(vals.min()),'max':float(vals.max()),
        'q001':float(np.quantile(vals,0.001)),
        'q999':float(np.quantile(vals,0.999)),
    }

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--m',type=int,default=22)
    ap.add_argument('--seeds',default='11,29,47,83')
    args=ap.parse_args()
    seeds=[int(x) for x in args.seeds.split(',')]
    reps=[sobol_mean(args.m,s) for s in seeds]
    means=np.array([r['mean'] for r in reps])
    mean=float(means.mean()); rep_sd=float(means.std(ddof=1)) if len(means)>1 else 0.0

    # Exact high-symmetry checks.
    k0=(2.0/3.0)*math.log(3.0)
    # Algebraic determinant check on random phases.
    omega=np.exp(2j*np.pi/3)
    X=np.array([[0,0,1],[1,0,0],[0,1,0]],complex)
    Z=np.diag([1,omega,omega**2])
    I=np.eye(3,dtype=complex)
    rng=np.random.default_rng(210963)
    det_err=0.0
    for _ in range(100):
        th=rng.uniform(-math.pi,math.pi)
        lam=np.exp(1j*th)
        lhs=np.linalg.det(lam**2*I+lam*X+Z)
        rhs=lam**6+lam**3+1
        det_err=max(det_err,float(abs(lhs-rhs)))

    report={
      'status':'PASS_CANONICAL_TEMPORAL_MONODROMY_SPECTRAL_INTEGRAL',
      'external_particle_data_used':False,
      'route_lengths':list(D),
      'completion_rule':'P_a(k)=U_C8(k)^d_a; unique within the declared one-generator temporal-semigroup completion P_{d+d\' }=P_d P_d\', P_0=I.',
      'exact_integrand':'kappa(k)=ln(3)-(1/3) ln|1+2 cos(3 theta(k))|; cos(theta)=prod cos(k_i)-prod sin(k_i)',
      'exact_kappa_at_k0':k0,
      'determinant_identity_max_abs_error':det_err,
      'qmc_replicates':reps,
      'K_stream_mean':mean,
      'K_stream_interreplicate_sd':rep_sd,
      'historical_inverse_target':TARGET,
      'target_minus_stream':TARGET-mean,
      'ratio_target_over_stream':TARGET/mean,
      'verdict':'The independently evaluated canonical free-stream compression action is not 6.72754375695... . The historical value is therefore not generated by the C8 temporal monodromy spectrum alone; any change must arise from the genuinely coupled gauge/dressing/chiral environment.',
    }
    assert det_err < 1e-12
    assert abs(mean-TARGET)>1.0
    OUT.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__': main()
