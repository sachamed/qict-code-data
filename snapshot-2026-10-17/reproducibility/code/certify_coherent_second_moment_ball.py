#!/usr/bin/env python3
"""Exact two-moment matrix-ball geometry for coherent unitary compression.

For U unitary and V^*V=I, C1=A, C2=A^2+D_left K D_right,
D_left=(I-AA^*)^1/2, D_right=(I-A^*A)^1/2, ||K||<=1.
All examples are mathematical controls, NEVER physical charged G2 moments.
No missing coherent C10 maps or Kato states are generated by this script.
"""
from __future__ import annotations
import hashlib, json, argparse
from pathlib import Path
import numpy as np
from scipy.linalg import eigh

ROOT=Path(__file__).resolve().parents[1]

def sqrt_psd(H, tol=2e-11):
    H=(H+H.conj().T)*0.5
    eig,V=eigh(H)
    if eig.min() < -tol: raise AssertionError(f'negative eigenvalue {eig.min()}')
    return (V*np.sqrt(np.maximum(eig,0.)))@V.conj().T

def psd_check(M):
    return float(eigh((M+M.conj().T)*.5,eigvals_only=True)[0])

def toeplitz_three(A,B):
    d=A.shape[0];I=np.eye(d,dtype=complex)
    return np.block([[I,A,B],[A.conj().T,I,A],[B.conj().T,A.conj().T,I]])

def matrix_ball(A,B,tol=2e-9):
    d=A.shape[0];I=np.eye(d,dtype=complex)
    DL=sqrt_psd(I-A@A.conj().T)
    DR=sqrt_psd(I-A.conj().T@A)
    E=B-A@A
    K=np.linalg.pinv(DL,rcond=1e-10)@E@np.linalg.pinv(DR,rcond=1e-10)
    reconstruct=DL@K@DR
    residual=float(np.linalg.norm(E-reconstruct,ord=2))
    kmax=float(np.linalg.norm(K,ord=2))
    toeig=psd_check(toeplitz_three(A,B))
    S=np.block([[I-A@A.conj().T,E],[E.conj().T,I-A.conj().T@A]])
    seig=psd_check(S)
    # Near-unit singular values make Moore-Penrose K numerically ill-conditioned;
    # positivity of the Schur complement is the stable necessary and sufficient
    # test, whereas the computed K may exceed 1 by roundoff magnification.
    pos_svals = [x for DD in (DL,DR) for x in np.linalg.svd(DD,compute_uv=False) if x > 1e-10]
    well_conditioned = bool(pos_svals) and min(pos_svals)>1e-5
    if residual>tol or (well_conditioned and kmax>1+tol) or toeig < -tol or seig < -tol:
        raise AssertionError(f'Matrix-ball certificate failed: residual={residual}, ||K||={kmax}, Toeplitz={toeig}, Schur={seig}')
    return {'matrix_size':d,'operator_norm_A':float(np.linalg.norm(A,2)),
            'K_operator_norm':kmax,'K_norm_is_numerically_certified':well_conditioned,'reconstruction_residual_op':residual,
            'toeplitz_min_eigenvalue':toeig,'schur_min_eigenvalue':seig,
            'defect_left_rank':int(np.linalg.matrix_rank(DL,tol=1e-9)),
            'defect_right_rank':int(np.linalg.matrix_rank(DR,tol=1e-9))}

def phase_family(theta):
    p=1/7; a=np.sqrt(1-p); b=np.sqrt(p)
    return np.array([[a,b],[-np.exp(1j*theta)*b,np.exp(1j*theta)*a]],dtype=complex)

def six_blocks(phases):
    assert len(phases)==6
    U=np.zeros((12,12),complex);V=np.zeros((12,6),complex)
    for j,phi in enumerate(phases):
        U[2*j:2*j+2,2*j:2*j+2]=phase_family(phi);V[2*j,j]=1
    return U,V

def C(U,V,n):
    return V.conj().T@np.linalg.matrix_power(U,n)@V

def check_unitary(U,tol=1e-10):
    defect=float(np.linalg.norm(U.conj().T@U-np.eye(len(U)),ord='fro'))
    if defect>tol:raise AssertionError(f'unitarity defect={defect}')
    return defect

def finite_archived_control():
    fn=ROOT/'data/common_physical_chain/SU2_B0_ISOLATED_RIESZ_KATO.npz'
    with np.load(fn,allow_pickle=False) as d: A=np.asarray(d['U'],complex)
    n=A.shape[0]; I=np.eye(n,dtype=complex)
    # Numerical SVD projection clips roundoff singular values 1+O(eps)
    # and computes Julia defects on singular vectors (stable at rank deficiency).
    L,svals,Rh=np.linalg.svd(A,full_matrices=True)
    sval=np.minimum(svals,1.)
    Aclip=(L*sval)@Rh
    gap=np.sqrt(np.maximum(0.,1-sval**2))
    DL=(L*gap)@L.conj().T
    R=Rh.conj().T
    DR=(R*gap)@R.conj().T
    W=np.block([[Aclip,DL],[DR,-Aclip.conj().T]])
    uv=check_unitary(W,5e-11)
    V=np.eye(2*n,6,dtype=complex)
    return {'source':'data/common_physical_chain/SU2_B0_ISOLATED_RIESZ_KATO.npz',
            'classification':'FINITELY DILATED SU2 REDUCED-OPERATOR CONTROL; NOT PHYSICAL G2',
            'dilation_dim':2*n,'unitarity_defect_fro':uv,'svd_clip_difference_fro':float(np.linalg.norm(Aclip-A)),
            'moment_ball':matrix_ball(C(W,V,1),C(W,V,2))}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--out',type=Path,default=ROOT/'results/COHERENT_SECOND_MOMENT_BALL_CERTIFICATE.json')
    args=ap.parse_args()
    a=np.sqrt(6/7);p=1/7
    cases={}
    for name,phases in {
        'all_zero':[0]*6,'all_pi':[np.pi]*6,
        'six_independent':[0,np.pi/7,np.pi/5,np.pi/3,np.pi/2,np.pi],
        'all_pi_over_two':[np.pi/2]*6}.items():
        U,V=six_blocks(phases)
        udef=check_unitary(U)
        moments=np.array([C(U,V,n) for n in range(13)])
        if np.linalg.norm(moments[0]-np.eye(6))>1e-12:raise AssertionError('source Gram')
        if np.linalg.norm(moments[1]-a*np.eye(6))>1e-12:raise AssertionError('C1 phase dependent')
        predicted=np.diag([a*a-p*np.exp(1j*t) for t in phases])
        if np.linalg.norm(moments[2]-predicted)>1e-12:raise AssertionError('C2 analytical')
        maxrec=0.
        for j,t in enumerate(phases):
            z=np.exp(1j*t)
            for nn in range(11):
                expected=a*(1+z)*moments[nn+1,j,j]-z*moments[nn,j,j]
                maxrec=max(maxrec,float(abs(moments[nn+2,j,j]-expected)))
        if maxrec>1e-11:raise AssertionError('higher moment recurrence')
        cases[name]={'unitarity_defect_fro':udef,'moment_ball':matrix_ball(moments[1],moments[2]),
                     'recurrence_error_max':maxrec,'moment_C2_diagonal_re':np.real(np.diag(moments[2])).tolist(),
                     'moment_C2_diagonal_im':np.imag(np.diag(moments[2])).tolist(),
                     'phase_list_radians':phases}
    U0,V0=six_blocks([0]*6)
    Upi,Vpi=six_blocks([np.pi]*6)
    diff=float(np.linalg.norm(C(U0,V0,2)-C(Upi,Vpi,2),2))
    if abs(diff-2/7)>1e-12:raise AssertionError('phase diameter')
    if np.max(np.abs(np.abs(U0)**2-np.abs(Upi)**2))>1e-14:raise AssertionError('transition populations differ')
    rng=np.random.default_rng(20261011)
    random_errors=[]
    for ix in range(20):
        X=rng.standard_normal((16,16))+1j*rng.standard_normal((16,16))
        U,_=np.linalg.qr(X)
        Y=rng.standard_normal((16,6))+1j*rng.standard_normal((16,6))
        V,_=np.linalg.qr(Y)
        r=matrix_ball(C(U,V,1),C(U,V,2))
        random_errors.append(r)
    statusfile=ROOT/'results/physical_g2_execution/PHYSICAL_G2_CONTRACT_AUDIT.json'
    status=json.loads(statusfile.read_text())
    not_available=[k for k,v in status['physical_contract_checks'].items() if not v]
    out={'status':'PASS_2_MOMENT_OPERATOR_BALL_STRUCTURAL_CERTIFICATE',
         'scope':'Exact unitary-compression mathematics; no physical QICT charged mass, gravity or UV limit extracted',
         'theorem':'C2=A^2+sqrt(I-AA*) K sqrt(I-A*A), ||K||<=1, equivalent to PSD T2 for normalized moments',
         'analytic_phase_family':{'p':'1/7','C0':'I6','C1':'sqrt(6/7) I6',
             'C2':'(6/7)I6-(1/7)diag(exp(i theta_j))',
             'same_transition_probabilities_all_phases':True,
             'C2_operator_norm_difference_theta0_vs_pi':diff,
             'sharp_matrix_disk_radius':'1/7'},
         'phase_cases':cases,'random_unitary_benchmarks':{'trials':len(random_errors),
             'max_factorization_residual':max(x['reconstruction_residual_op'] for x in random_errors),
             'max_K_norm':max(x['K_operator_norm'] for x in random_errors),
             'min_toeplitz_eigenvalue':min(x['toeplitz_min_eigenvalue'] for x in random_errors)},
         'archived_Su2_finite_control':finite_archived_control(),
         'physical_input_audit':{'complete':len(status['physical_contract_checks'])-len(not_available),
                'total':len(status['physical_contract_checks']),'missing':sorted(not_available),
                'physical_G2_promoted':False},
         'no_new_physics_fitted':True}
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text(json.dumps(out,indent=2,sort_keys=True,default=lambda x:float(x))+'\n')
    print(f'PASS matrix ball: {len(random_errors)} random controls, four phase families; 2/7 sharp second moment diameter; physical input {out["physical_input_audit"]["complete"]}/{out["physical_input_audit"]["total"]}')
    print(args.out)

if __name__=='__main__':main()
