#!/usr/bin/env python3
"""Prospective parameter-free mass-ratio extraction from converged G2 physical spectral edges.

This script does not read experimental mass tables. It requires a fixed prediction specification
and a G2 edge payload generated by the compact 3D interacting calculation.
If either is absent, the observable retains DEFINED_OBSERVABLE status;
no finite or free-theory surrogate is substituted.
"""
from pathlib import Path
import json, math, hashlib
import numpy as np
ROOT=Path(__file__).resolve().parents[2]
DATA=ROOT/'data'; CERT=ROOT/'certificates'
EDGE=DATA/'g2_physical_compact_3d_edges.json'
LOCK=ROOT/'preregistration'/'QICT_PREDICTION_LOCK.json'
OUT=DATA/'qict_prospective_mass_ratios.json'
COUT=CERT/'QICT_PROSPECTIVE_MASS_SPECTRUM.json'
SPECIES=['e','mu','tau','u','d','s','c','b','t']
PRIMARY=[('mu','e'),('tau','e'),('t','b'),('c','s'),('s','d'),('b','s')]
def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
if not (EDGE.exists() and LOCK.exists()):
    out={'status':'DEFINED_OBSERVABLE','claim_status':'DEFINED_OBSERVABLE','reason':'The converged full-3D interacting G2 edge payload and fixed precomparison specification are required for numerical evaluation. Finite C7 phases, strip phases, tangent resistances, and external particle masses are excluded from the parameter-free extraction.','external_mass_data_read':False}
    COUT.write_text(json.dumps(out,indent=2)+'\n'); print(json.dumps(out,indent=2)); raise SystemExit(0)
obj=json.loads(EDGE.read_text()); names=obj['species']; eps=np.asarray(obj['epsilon_edge'],float)
Cn=np.asarray(obj['cov_numerical'],float); Cr=np.asarray(obj['cov_regulator'],float); C=Cn+Cr
assert names==SPECIES and eps.shape==(9,) and C.shape==(9,9)
assert np.all(eps>0) and np.min(np.linalg.eigvalsh((C+C.T)/2))>-1e-12
idx={s:i for i,s in enumerate(names)}
def ratio(a,b):
    i,j=idx[a],idx[b]; r=eps[i]/eps[j]
    g=np.zeros(9); g[i]=1/eps[j]; g[j]=-eps[i]/eps[j]**2
    sn=math.sqrt(max(0,float(g@Cn@g))); sr=math.sqrt(max(0,float(g@Cr@g)))
    return {'numerator':a,'denominator':b,'ratio':r,'sigma_numerical':sn,'sigma_regulator':sr,'sigma_total':math.hypot(sn,sr)}
ratios=[ratio(a,b) for a,b in PRIMARY]
out={'status':'COMPUTED','claim_status':'COMPUTED','external_mass_data_read':False,'edge_payload_sha256':sha(EDGE),'lock_sha256':sha(LOCK),'species':names,'epsilon_edge':eps.tolist(),'ratios':ratios,'absolute_mass_status':'REQUIRES_INDEPENDENT_TAU_STAR_OR_A_DERIVED_DIMENSIONFUL_SECTOR'}
OUT.write_text(json.dumps(out,indent=2)+'\n'); COUT.write_text(json.dumps(out,indent=2)+'\n'); print(json.dumps(out,indent=2))
