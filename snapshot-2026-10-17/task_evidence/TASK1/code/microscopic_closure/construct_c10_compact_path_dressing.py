#!/usr/bin/env python3
"""Construct the C10 Gauss minimizer as an exact acyclic path-mixture tensor.

For the finite BCC Dirichlet ball, solve L phi = delta_0. Orient every edge in
strictly decreasing phi. The positive electric flux E_{v->w}=phi(v)-phi(w)
(including edges from boundary vertices to the collapsed Dirichlet sink) is a
unit source flow. Its normalized outgoing flux defines a parameter-free Markov
kernel on a DAG. The probability that the source path uses an oriented edge is
then exactly E_{v->w}. This supplies a compact path-sum dressing without
enumerating exponentially many geodesics.
"""
from __future__ import annotations
import argparse,json,hashlib,math
from pathlib import Path
from itertools import product
import numpy as np
from scipy.sparse import lil_matrix
from scipy.sparse.linalg import cg
ROOT=Path(__file__).resolve().parents[2]
OUTDIR=ROOT/'results'/'microscopic_closure';OUTDIR.mkdir(parents=True,exist_ok=True)
DIRS=list(product((-1,1),repeat=3)); SRC=(0,0,0); SINK='BOUNDARY_SINK'

def ball(R):
    dist={SRC:0};front=[SRC]
    for _ in range(R):
        nxt=[]
        for x in front:
            for d in DIRS:
                y=tuple(x[i]+d[i] for i in range(3))
                if y not in dist:dist[y]=dist[x]+1;nxt.append(y)
        front=nxt
    return dist

def solve(R):
    dist=ball(R);nodes=list(dist);idx={x:i for i,x in enumerate(nodes)};n=len(nodes)
    L=lil_matrix((n,n),dtype=float)
    for x,i in idx.items():
        L[i,i]=8.0
        for d in DIRS:
            y=tuple(x[k]+d[k] for k in range(3));j=idx.get(y)
            if j is not None:L[i,j]-=1.0
    b=np.zeros(n);b[idx[SRC]]=1.0
    phi,info=cg(L.tocsr(),b,rtol=2e-14,atol=0.0,maxiter=50000)
    if info:raise RuntimeError((R,info))
    return dist,nodes,idx,phi

def build(R,tol=5e-14):
    dist,nodes,idx,phi=solve(R)
    # Count each undirected internal edge once; add one sink edge for every missing BCC neighbor.
    out={x:[] for x in nodes};sink_in=[];edges=[]
    for x in nodes:
        ix=idx[x];px=float(phi[ix])
        for d in DIRS:
            y=tuple(x[k]+d[k] for k in range(3));jy=idx.get(y)
            if jy is None:
                # Dirichlet outside has phi=0. Each missing lattice bond remains distinct.
                f=px
                if f>tol:
                    out[x].append((SINK,f));sink_in.append((x,f));edges.append((x,SINK,f))
            elif ix<jy:
                py=float(phi[jy]);f=px-py
                if f>tol:out[x].append((y,f));edges.append((x,y,f))
                elif f<-tol:out[y].append((x,-f));edges.append((y,x,-f))
    # Divergence including sink bonds.
    div={x:0.0 for x in nodes}
    for a,b,f in edges:
        div[a]+=f
        if b!=SINK:div[b]-=f
    max_harm=max(abs(div[x]) for x in nodes if x!=SRC)
    srcdiv=div[SRC];sinkflux=sum(f for _,f in sink_in)
    # DAG dynamic path mass from source. Strict phi descent orders all internal transitions.
    order=sorted(nodes,key=lambda x:float(phi[idx[x]]),reverse=True)
    mass={x:0.0 for x in nodes};mass[SRC]=1.0;sinkmass=0.0
    max_kernel_norm=0.0;edge_occ_err=0.0
    for x in order:
        F=sum(f for _,f in out[x])
        if F<=tol:
            continue
        # For source F=1; for harmonic nodes F equals total inflow. Thus mass[x]=F.
        max_kernel_norm=max(max_kernel_norm,abs(sum(f/F for _,f in out[x])-1.0))
        for y,f in out[x]:
            p=f/F;occ=mass[x]*p
            edge_occ_err=max(edge_occ_err,abs(occ-f))
            if y==SINK:sinkmass+=occ
            else:mass[y]+=occ
    # Flow/mass identity at nodes.
    node_flow_err=0.0
    incoming={x:0.0 for x in nodes};incoming[SRC]=1.0
    for a,b,f in edges:
        if b!=SINK:incoming[b]+=f
    for x in nodes:node_flow_err=max(node_flow_err,abs(mass[x]-incoming[x]))
    # Count active edges and potential monotonicity.
    mono=min((float(phi[idx[a]])-(0.0 if b==SINK else float(phi[idx[b]]))) for a,b,_ in edges)
    return {
      'R':R,'vertices':len(nodes),'active_oriented_edges':len(edges),'source_potential':float(phi[idx[SRC]]),
      'source_divergence':srcdiv,'sink_flux':sinkflux,'max_harmonic_divergence_abs':max_harm,
      'sink_path_probability':sinkmass,'max_transition_normalization_residual':max_kernel_norm,
      'max_node_pathmass_flow_residual':node_flow_err,'max_edge_occupation_flux_residual':edge_occ_err,
      'minimum_active_potential_drop':mono,
      'path_tensor_definition':'D_q,R(x)=sum_gamma P_R(gamma) Pexp_gamma[U]^q, with P_R generated by normalized positive C10 flux',
      'gauge_covariance':'Every path has common source and collapsed boundary sink; under boundary-trivial gauge transformations all path holonomies transform with the same source factor, so the weighted sum is covariant.',
      'parameter_free':True,
      'checks_pass': bool(abs(srcdiv-1)<2e-11 and abs(sinkflux-1)<2e-11 and abs(sinkmass-1)<2e-11 and max_harm<2e-11 and edge_occ_err<2e-11 and node_flow_err<2e-11 and mono>0)
    }

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--maxR',type=int,default=12);a=ap.parse_args()
    rows=[build(R) for R in range(1,a.maxR+1)]
    cert={'status':'PASS_C10_COMPACT_PATH_DRESSING' if all(r['checks_pass'] for r in rows) else 'FAIL_C10_COMPACT_PATH_DRESSING',
          'external_particle_data_used':False,'construction':'acyclic positive-flow decomposition of the unique finite-volume C10 Dirichlet Gauss minimizer',
          'theorem':'For L phi=delta_x with zero Dirichlet exterior, orient each bond down the potential and set E=(phi_v-phi_w)_+. Harmonicity gives flow conservation away from x; strict potential descent makes the graph acyclic. The transition kernel p(v->w)=E_vw/sum_u E_vu therefore induces a source-to-boundary path measure whose expected edge occupation equals E_vw exactly.',
          'radii':rows,'max_R':a.maxR}
    txt=json.dumps(cert,indent=2)+'\n';out=OUTDIR/'C10_COMPACT_PATH_DRESSING.json';out.write_text(txt)
    print(json.dumps({'status':cert['status'],'max_R':a.maxR,'last':rows[-1],'sha256':hashlib.sha256(txt.encode()).hexdigest()},indent=2))
if __name__=='__main__':main()
