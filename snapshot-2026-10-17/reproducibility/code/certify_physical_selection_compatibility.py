def c7(k):
    c=np.cos(k);s=np.sin(k)
    u=float(np.prod(c)-np.prod(s))
    n=np.array([s[0]*c[1]*c[2]+c[0]*s[1]*s[2],
        c[0]*s[1]*c[2]-s[0]*c[1]*s[2],
        c[0]*c[1]*s[2]+s[0]*s[1]*c[2]])
    return u,n,1-float(np.prod(c))


